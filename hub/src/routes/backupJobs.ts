import type { FastifyInstance } from 'fastify';
import { ObjectId } from 'mongodb';
import { AgentRequestError, agentRequest, isOnline } from '../agents.js';
import { DEFAULT_TIMEZONE, HOSTS_NS, TOKEN_ID_RE, checkDatabase, clientState, checkJob, currentHash, groupConflict, isDatabaseKind, jobKind, jobView, normDatabase, refreshManaged, syncHost, type JobInput } from '../backupJobs.js';
import { backupJobs, backups, hosts, parseId } from '../db.js';
import type { BackupArchive, BackupJobKind, DatabaseDump, HostDoc } from '../types.js';
import { publish } from '../events.js';
import { createJob, jobDto } from '../jobs.js';
import { keepText, loadPbsSettings, policyFor } from '../pbs.js';
import { describeCalendar } from '../calendar.js';
import { config } from '../config.js';
import { isPluginJob } from '../nextcloud.js';

// A job generated by the Nextcloud AIO plugin changes through the plugin only.
const PLUGIN_LOCKED = 'job géré par le plugin Nextcloud AIO : le modifier depuis le plugin';

const jobProps = {
  name: { type: 'string', minLength: 1, maxLength: 64 },
  // a database job holds its dumps only (no directory): the count is checked by checkJob, per kind
  archives: {
    type: 'array',
    maxItems: 20,
    items: {
      type: 'object',
      required: ['name', 'path'],
      additionalProperties: false,
      properties: { name: { type: 'string', maxLength: 64 }, path: { type: 'string', maxLength: 1024 } },
    },
  },
  excludes: { type: 'array', maxItems: 100, items: { type: 'string', maxLength: 256 } },
  store: { type: 'string', maxLength: 64 },
  ns: { type: 'string', maxLength: 256 },
  backupId: { type: 'string', maxLength: 64 },
  schedule: { type: 'string', maxLength: 128 },
  timezone: { type: 'string', maxLength: 64 },
  enabled: { type: 'boolean' },
  kind: { type: 'string', enum: ['directories', 'postgres', 'mongodb'] },
  database: {
    type: ['object', 'null'],
    additionalProperties: false,
    required: ['databases', 'workDir', 'keep'],
    properties: {
      mode: { type: 'string', enum: ['databases', 'cluster'] },
      databases: { type: 'array', maxItems: 50, items: { type: 'string', maxLength: 64 } },
      container: { type: 'string', maxLength: 128 },
      workDir: { type: 'string', maxLength: 1024 },
      keep: { type: 'integer', minimum: 0, maximum: 30 },
    },
  },
} as const;

const required = ['name', 'archives', 'excludes', 'store', 'schedule', 'enabled'] as const;

// An agent that does not know database jobs would back up nothing.
function databaseRefused(host: HostDoc, kind: BackupJobKind) {
  if (!isDatabaseKind(kind)) return null;
  return clientState(host.capabilities).databases ? null : "l'agent de cet hôte ne sait pas sauvegarder de base : le mettre à jour d'abord";
}

// What is stored for a job of this kind: a database job holds its dumps only.
function normInput(b: JobInput, kind: BackupJobKind) {
  const db = isDatabaseKind(kind);
  return { ...b, kind, database: normDatabase(kind, b.database), archives: db ? [] : b.archives, excludes: db ? [] : b.excludes };
}

async function changed(hostId: ObjectId) {
  await refreshManaged();
  await syncHost(hostId);
  publish('backups', {});
}

// Backups of directories run by the agent of a host (see backupJobs.ts). Settings of a host: admin;
// running a job now: operator too (roles.ts).
export function registerBackupJobRoutes(app: FastifyInstance) {
  app.get<{ Params: { id: string } }>('/api/hosts/:id/backup-jobs', async (req, reply) => {
    const _id = parseId(req.params.id);
    const host = _id && (await hosts.findOne({ _id }));
    if (!host) return reply.code(404).send({ error: 'host not found' });
    const pbs = await loadPbsSettings();
    const list = await backupJobs.find({ hostId: _id }).sort({ name: 1 }).toArray();
    return {
      // the agent runs the client natively or in a container; how it can be installed
      ...clientState(host.capabilities),
      credential: host.pbsCredential ? { tokenId: host.pbsCredential.tokenId, updatedAt: host.pbsCredential.updatedAt, store: host.pbsCredential.store ?? null } : null,
      sync: host.backupSync ? { ...host.backupSync, current: host.backupSync.hash === (await currentHash(host)) } : null,
      pbsReady: pbs.enabled && !!pbs.url,
      datastores: (pbs.datastores ?? []).map((d) => d.store),
      // retention the PBS applies to the namespace of each datastore (null: none, snapshots pile up)
      retention: Object.fromEntries(
        (pbs.datastores ?? []).map((d) => {
          const p = policyFor(pbs.prune ?? [], d.store, HOSTS_NS);
          return [d.store, p ? { keep: keepText(p.keep), schedule: p.schedule ? describeCalendar(p.schedule) : null, ns: p.ns } : null];
        }),
      ),
      timezone: DEFAULT_TIMEZONE,
      // Nextcloud AIO plugin shown (BACKUP_NEXTCLOUD_AIO), and settings of this host
      nextcloudPlugin: config.backupNextcloudAio,
      nextcloudSettings: host.nextcloud ?? null,
      jobs: list.map(jobView),
    };
  });

  app.put<{ Params: { id: string }; Body: { tokenId: string; tokenSecret?: string } | null }>(
    '/api/hosts/:id/pbs-credential',
    {
      schema: {
        body: {
          type: ['object', 'null'],
          additionalProperties: false,
          required: ['tokenId'],
          properties: { tokenId: { type: 'string', maxLength: 128 }, tokenSecret: { type: 'string', maxLength: 128 } },
        },
      },
    },
    async (req, reply) => {
      const _id = parseId(req.params.id);
      const host = _id && (await hosts.findOne({ _id }));
      if (!host) return reply.code(404).send({ error: 'host not found' });
      if (req.body === null) {
        await hosts.updateOne({ _id }, { $unset: { pbsCredential: '' } });
      } else {
        const tokenId = req.body.tokenId.trim();
        const tokenSecret = req.body.tokenSecret?.trim() || host.pbsCredential?.tokenSecret;
        if (!TOKEN_ID_RE.test(tokenId)) return reply.code(400).send({ error: 'identifiant du jeton invalide (utilisateur@royaume!jeton)' });
        if (!tokenSecret) return reply.code(400).send({ error: 'secret du jeton requis' });
        // entered by hand: the datastore of its rights is not known
        await hosts.updateOne({ _id }, { $set: { pbsCredential: { tokenId, tokenSecret, updatedAt: new Date() } } });
      }
      await changed(_id);
      return { ok: true };
    },
  );

  app.post<{ Params: { id: string }; Body: JobInput }>(
    '/api/hosts/:id/backup-jobs',
    { schema: { body: { type: 'object', additionalProperties: false, required: [...required, 'backupId'], properties: jobProps } } },
    async (req, reply) => {
      const _id = parseId(req.params.id);
      const host = _id && (await hosts.findOne({ _id }));
      if (!host) return reply.code(404).send({ error: 'host not found' });
      if (!clientState(host.capabilities).mode) return reply.code(409).send({ error: "client PBS absent sur cet hôte : l'installer d'abord" });
      const pbs = await loadPbsSettings();
      // namespace and time zone are fixed: Hosts, and the time zone of the hub (TZ)
      const body = { ...normInput(req.body, req.body.kind ?? 'directories'), ns: HOSTS_NS, timezone: DEFAULT_TIMEZONE };
      const err = checkJob(body, true);
      if (err) return reply.code(400).send({ error: err });
      const refused = databaseRefused(host, body.kind);
      if (refused) return reply.code(409).send({ error: refused });
      const conflict = await groupConflict(_id, body.store, body.ns, body.backupId!);
      if (conflict) return reply.code(409).send({ error: conflict });
      const now = new Date();
      const doc = {
        _id: new ObjectId(),
        hostId: _id,
        name: body.name.trim(),
        archives: body.archives,
        excludes: body.excludes,
        store: body.store,
        ns: body.ns,
        backupId: body.backupId!,
        schedule: body.schedule.trim(),
        timezone: body.timezone,
        enabled: body.enabled,
        kind: body.kind,
        database: body.database,
        createdAt: now,
        updatedAt: now,
        lastRun: null,
      };
      await backupJobs.insertOne(doc);
      await changed(_id);
      reply.code(201);
      return jobView(doc);
    },
  );

  // The backup id (group on the PBS) is fixed: a new one would start a new history.
  app.put<{ Params: { jobId: string }; Body: JobInput }>(
    '/api/backup-jobs/:jobId',
    { schema: { body: { type: 'object', additionalProperties: false, required: [...required], properties: jobProps } } },
    async (req, reply) => {
      const _id = parseId(req.params.jobId);
      const cur = _id && (await backupJobs.findOne({ _id }));
      if (!cur) return reply.code(404).send({ error: 'job introuvable' });
      if (isPluginJob(cur)) return reply.code(409).send({ error: PLUGIN_LOCKED });
      if (req.body.backupId !== undefined && req.body.backupId !== cur.backupId) return reply.code(400).send({ error: "l'identifiant de sauvegarde ne change pas" });
      // the kind is fixed too: its archives are of another nature
      const kind = jobKind(cur);
      if (req.body.kind !== undefined && req.body.kind !== kind) return reply.code(400).send({ error: 'le type de sauvegarde ne change pas' });
      const body = { ...normInput(req.body, kind), ns: HOSTS_NS, timezone: cur.timezone };
      const err = checkJob(body, false);
      if (err) return reply.code(400).send({ error: err });
      const host = await hosts.findOne({ _id: cur.hostId });
      const refused = host && databaseRefused(host, kind);
      if (refused) return reply.code(409).send({ error: refused });
      if (body.store !== cur.store || body.ns !== cur.ns) {
        const conflict = await groupConflict(cur.hostId, body.store, body.ns, cur.backupId, cur._id);
        if (conflict) return reply.code(409).send({ error: conflict });
      }
      const set = {
        name: body.name.trim(),
        archives: body.archives,
        excludes: body.excludes,
        store: body.store,
        ns: body.ns,
        schedule: body.schedule.trim(),
        timezone: body.timezone,
        enabled: body.enabled,
        kind,
        database: body.database,
        updatedAt: new Date(),
      };
      // the first form of the database jobs goes
      await backupJobs.updateOne({ _id }, { $set: set, $unset: { prepare: '' } });
      await changed(cur.hostId);
      return jobView({ ...cur, ...set, prepare: undefined });
    },
  );

  // The snapshots stay on the PBS; the group becomes an orphan.
  app.delete<{ Params: { jobId: string } }>('/api/backup-jobs/:jobId', async (req, reply) => {
    const _id = parseId(req.params.jobId);
    const cur = _id && (await backupJobs.findOne({ _id }));
    if (!cur) return reply.code(404).send({ error: 'job introuvable' });
    if (isPluginJob(cur)) return reply.code(409).send({ error: PLUGIN_LOCKED });
    await backupJobs.deleteOne({ _id });
    await changed(cur.hostId);
    return reply.code(204).send();
  });

  // Checks a database job on the host before saving it: tools, databases of the server and their size,
  // free space of the work directory (form of a job, admin).
  app.post<{ Params: { id: string }; Body: { kind: 'postgres' | 'mongodb'; database: DatabaseDump } }>(
    '/api/hosts/:id/backup-database-check',
    {
      schema: {
        body: {
          type: 'object',
          additionalProperties: false,
          required: ['kind', 'database'],
          properties: { kind: { type: 'string', enum: ['postgres', 'mongodb'] }, database: { ...jobProps.database, type: 'object' } },
        },
      },
    },
    async (req, reply) => {
      const _id = parseId(req.params.id);
      const host = _id && (await hosts.findOne({ _id }));
      if (!host) return reply.code(404).send({ error: 'host not found' });
      const { kind } = req.body;
      const database = normDatabase(kind, req.body.database)!;
      const err = checkDatabase(kind, database, false);
      if (err) return reply.code(400).send({ error: err });
      const refused = databaseRefused(host, kind);
      if (refused) return reply.code(409).send({ error: refused });
      if (!isOnline(host._id.toHexString())) return reply.code(409).send({ error: 'hôte hors ligne' });
      try {
        return await agentRequest(host._id.toHexString(), 'backup_database_check', { backupKind: kind, database }, 75_000);
      } catch (e) {
        // answer of the agent (container stopped, no postgres user…) or no answer: shown in the form
        if (e instanceof AgentRequestError) return reply.code(502).send({ error: e.message });
        throw e;
      }
    },
  );

  // Estimates the size of the directories of a job form with its exclusions, to check the filters (admin).
  app.post<{ Params: { id: string }; Body: { archives: BackupArchive[]; excludes: string[] } }>(
    '/api/hosts/:id/backup-estimate',
    {
      schema: {
        body: {
          type: 'object',
          additionalProperties: false,
          required: ['archives', 'excludes'],
          properties: { archives: { ...jobProps.archives, minItems: 1 }, excludes: jobProps.excludes },
        },
      },
    },
    async (req, reply) => {
      const _id = parseId(req.params.id);
      const host = _id && (await hosts.findOne({ _id }));
      if (!host) return reply.code(404).send({ error: 'host not found' });
      if (!(host.capabilities ?? []).includes('backup_estimate')) return reply.code(409).send({ error: "l'agent de cet hôte ne sait pas estimer : le mettre à jour d'abord" });
      if (!isOnline(host._id.toHexString())) return reply.code(409).send({ error: 'hôte hors ligne' });
      try {
        return await agentRequest(host._id.toHexString(), 'backup_estimate', { estArchives: req.body.archives, estExcludes: req.body.excludes }, 200_000);
      } catch (e) {
        if (e instanceof AgentRequestError) return reply.code(502).send({ error: e.message });
        throw e;
      }
    },
  );

  // Installs the PBS client on the host: Proxmox repository + package, or the client image (admin).
  app.post<{ Params: { id: string }; Body: { method: 'apt' | 'docker' } }>(
    '/api/hosts/:id/backup-client',
    { schema: { body: { type: 'object', required: ['method'], additionalProperties: false, properties: { method: { type: 'string', enum: ['apt', 'docker'] } } } } },
    async (req, reply) => {
      const _id = parseId(req.params.id);
      const host = _id && (await hosts.findOne({ _id }));
      if (!host) return reply.code(404).send({ error: 'host not found' });
      if (!isOnline(host._id.toHexString())) return reply.code(409).send({ error: 'hôte hors ligne' });
      if (!clientState(host.capabilities).install.includes(req.body.method)) {
        return reply.code(400).send({ error: req.body.method === 'apt' ? 'installation APT impossible ici (Debian bookworm / trixie amd64 uniquement)' : 'installation Docker impossible ici (Docker sur amd64 uniquement)' });
      }
      // the image to pull is the one of the settings, sent with the definition
      await syncHost(host._id);
      const job = await createJob(host, 'backup_install', [], 'manual', { method: req.body.method });
      reply.code(202);
      return jobDto(job);
    },
  );

  app.post<{ Params: { jobId: string } }>('/api/backup-jobs/:jobId/run', async (req, reply) => {
    const _id = parseId(req.params.jobId);
    const bj = _id && (await backupJobs.findOne({ _id }));
    if (!bj) return reply.code(404).send({ error: 'job introuvable' });
    const host = await hosts.findOne({ _id: bj.hostId });
    if (!host) return reply.code(404).send({ error: 'host not found' });
    if (!isOnline(host._id.toHexString())) return reply.code(409).send({ error: 'hôte hors ligne' });
    if (!host.capabilities?.includes('backup')) return reply.code(400).send({ error: "l'agent de cet hôte ne sait pas sauvegarder (client PBS absent, ou agent à mettre à jour)" });
    const g = await backups.findOne({ 'managed.jobId': bj._id.toHexString() });
    if (g?.managed && !g.managed.synced) return reply.code(409).send({ error: "l'agent n'a pas encore appliqué la définition de ce job" });
    const job = await createJob(host, 'backup_run', [], 'manual', { backupJob: bj._id.toHexString(), backupJobName: bj.name });
    reply.code(202);
    return jobDto(job);
  });
}
